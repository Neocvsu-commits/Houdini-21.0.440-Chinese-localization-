    for source, translation in LABS_BASE_TRANSLATIONS.items():
        entries[f"Labs {source}"] = f"Labs {translation}"
        # Some Tab-menu contexts omit the vendor prefix from the displayed
        # label.  Add that exact source only when no reviewed entry exists.
        current = entries.get(source, existing.get(source))
        if current is None or current == source:
            entries[source] = translation

    document["translations"] = dict(sorted(entries.items()))
    SUPPLEMENT.write_text(
        json.dumps(document, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    if NODE_LABELS.exists():
        payload = json.loads(NODE_LABELS.read_text(encoding="utf-8"))
        merged = load_all_existing()
        missing = sorted(
            {
                record["label"]
                for records in payload["categories"].values()
                for record in records
                if not record["hidden"]
                and re.search(r"[A-Za-z]", record["label"])
                and record["label"] not in merged
            }
        )
        if missing:
            raise SystemExit(
                "Visible Tab-menu labels still missing:\n" + "\n".join(missing)
            )
        untranslated = sorted(
            {
                record["label"]
                for records in payload["categories"].values()
                for record in records
                if not record["hidden"]
                and re.search(r"[A-Za-z]", record["label"])
                and merged.get(record["label"]) == record["label"]
                and record["label"] not in IDENTITY_ALLOWLIST
            }
        )
        if untranslated:
            raise SystemExit(
                "Visible Tab-menu labels still use unchanged English:\n"
                + "\n".join(untranslated)
            )

    print(f"wrote {len(entries)} Houdini 21 supplement entries")
    return 0


